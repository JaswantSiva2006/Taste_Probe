/**
 * The app requires an HTTPS Qloo base URL (kept as a production rule), so the stub
 * serves HTTPS with a throwaway self-signed localhost certificate generated by openssl.
 * Only the QA child server trusts it (NODE_TLS_REJECT_UNAUTHORIZED=0 in that process).
 */
function certificate() {
  const dir = resolve(".artifacts/qloo-stub");
  const key = resolve(dir, "key.pem");
  const cert = resolve(dir, "cert.pem");
  if (!existsSync(cert)) {
    mkdirSync(dir, { recursive: true });
    const r = spawnSync("openssl", ["req", "-x509", "-newkey", "rsa:2048", "-nodes", "-keyout", key, "-out", cert, "-days", "7", "-subj", "/CN=localhost"], { stdio: "ignore" });
    if (r.status !== 0) throw new Error("openssl is required to create the QA stub certificate");
  }
  return { key: readFileSync(key), cert: readFileSync(cert) };
}

export function startQlooStub() {
  const server = createServer(certificate(), (req, res) => {
    const url = new URL(req.url ?? "/", "http://stub");
    const send = (body) => {
      res.writeHead(200, { "content-type": "application/json" });
      res.end(JSON.stringify(body));
    };
    if (url.pathname === "/search") return send({ results: [INTERSTELLAR] });
    if (url.pathname === "/v2/insights") return send({ success: true, results: { entities: ARTISTS } });
    res.writeHead(404).end();
  });
  return new Promise((resolve) => server.listen(0, "127.0.0.1", () => resolve(server)));
}
